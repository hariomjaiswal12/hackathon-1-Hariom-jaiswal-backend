const BOOKING_STATUS = Object.freeze({
  PENDING: 'PENDING',
  CONFIRMED: 'CONFIRMED',
  ARRIVED: 'ARRIVED',
  SEATED: 'SEATED',
  COMPLETED: 'COMPLETED',
  CANCELLED: 'CANCELLED',
  NO_SHOW: 'NO_SHOW',
});

const BOOKING_STATUSES = Object.freeze(Object.values(BOOKING_STATUS));

const ACTIVE_BOOKING_STATUSES = Object.freeze([
  BOOKING_STATUS.PENDING,
  BOOKING_STATUS.CONFIRMED,
  BOOKING_STATUS.ARRIVED,
  BOOKING_STATUS.SEATED,
]);

const RESCHEDULABLE_BOOKING_STATUSES = ACTIVE_BOOKING_STATUSES;

const ALLOWED_BOOKING_TRANSITIONS = Object.freeze({
  [BOOKING_STATUS.PENDING]: Object.freeze([
    BOOKING_STATUS.CONFIRMED,
    BOOKING_STATUS.CANCELLED,
  ]),
  [BOOKING_STATUS.CONFIRMED]: Object.freeze([
    BOOKING_STATUS.ARRIVED,
    BOOKING_STATUS.CANCELLED,
    BOOKING_STATUS.NO_SHOW,
  ]),
  [BOOKING_STATUS.ARRIVED]: Object.freeze([
    BOOKING_STATUS.SEATED,
    BOOKING_STATUS.CANCELLED,
    BOOKING_STATUS.NO_SHOW,
  ]),
  [BOOKING_STATUS.SEATED]: Object.freeze([
    BOOKING_STATUS.COMPLETED,
    BOOKING_STATUS.CANCELLED,
  ]),
  [BOOKING_STATUS.COMPLETED]: Object.freeze([]),
  [BOOKING_STATUS.CANCELLED]: Object.freeze([]),
  [BOOKING_STATUS.NO_SHOW]: Object.freeze([]),
});

const BOOKING_HISTORY_ACTION = Object.freeze({
  CREATED: 'CREATED',
  STATUS_CHANGED: 'STATUS_CHANGED',
  RESCHEDULED: 'RESCHEDULED',
});

const BOOKING_HISTORY_ACTIONS = Object.freeze(Object.values(BOOKING_HISTORY_ACTION));

function canTransitionBooking(fromStatus, toStatus) {
  const allowed = ALLOWED_BOOKING_TRANSITIONS[fromStatus] || [];
  return allowed.includes(toStatus);
}

const BOOKING_SOURCE = Object.freeze({
  WEBSITE: 'WEBSITE',
  PHONE: 'PHONE',
  WHATSAPP: 'WHATSAPP',
  STAFF: 'STAFF',
  ADMIN: 'ADMIN',
});

const BOOKING_SOURCES = Object.freeze(Object.values(BOOKING_SOURCE));

const STAFF_BOOKING_SOURCES = Object.freeze([
  BOOKING_SOURCE.PHONE,
  BOOKING_SOURCE.WHATSAPP,
  BOOKING_SOURCE.STAFF,
]);

const ADMIN_BOOKING_SOURCES = Object.freeze([
  BOOKING_SOURCE.PHONE,
  BOOKING_SOURCE.WHATSAPP,
  BOOKING_SOURCE.STAFF,
  BOOKING_SOURCE.ADMIN,
]);

const MAX_TABLES_PER_BOOKING = 3;

module.exports = {
  BOOKING_STATUS,
  BOOKING_STATUSES,
  ACTIVE_BOOKING_STATUSES,
  RESCHEDULABLE_BOOKING_STATUSES,
  ALLOWED_BOOKING_TRANSITIONS,
  BOOKING_HISTORY_ACTION,
  BOOKING_HISTORY_ACTIONS,
  canTransitionBooking,
  BOOKING_SOURCE,
  BOOKING_SOURCES,
  STAFF_BOOKING_SOURCES,
  ADMIN_BOOKING_SOURCES,
  MAX_TABLES_PER_BOOKING,
};
